// =============================================================
// Starfall Chronicles — 跨文明合成链（本包核心卖点）
// 三条主链 + 一条暗线：
//   ① 上古之种(绿谷) → 生物燃料(铁锈)   —— 农耕↔工业
//   ② 精密零件(铁锈) → 量子核心(硅火)   —— 工业↔信息
//   ③ AI核心(硅火)   → 跃迁引擎(苍穹)   —— 信息↔星际
//   ④ 暗线：苍穹星的星门钥匙铭文，其实镌刻着上古之种的图案——
//      最原始的，才是最先进的。
// =============================================================

ServerEvents.recipes(event => {
  const { shaped, shapeless } = event;

  // ---- 配方删除演示（安全的无害移除，用于展示 .remove 用法）----
  // 移除原版时钟配方：铁锈星的钟表工业取代了原版简易钟。
  event.remove({ output: 'minecraft:clock' });

  // ---- 生物燃料的“农场外销”变体：绿谷星本地产油（弱化版，仅 1 罐）----
  // 若玩家想提前把种子攒起来带到铁锈星，也可在绿谷星直接装瓶 1 罐。
  // （配方位于数据包 data/starciv/recipes/biofuel_canister_campfire.json）

  // ---- 主链 ②③ 的汇总配方（可视化：JEI 里能看到全链条）----
  // ② 精密零件 → 量子核心（在 information.js 中，此处保留链条注释）
  // ③ 量子核心 → 跃迁核心 → 跃迁引擎（在 interstellar.js 中）

  // ---- “文明的代价”彩蛋配方 ----
  // 在铁锈星，你可以把 8 个生物燃料罐“冶炼”回 1 粒上古之种——
  // 代价是：种子退化为普通小麦种子（环保主义者路线）。
  shapeless('4x minecraft:wheat_seeds', ['4x starciv:biofuel_canister'])
    .stage('industrial');

  // ---- 星门钥匙升级：当持有星际文明阶段时，钥匙变为跃迁信物 ----
  // （保留物品本体，仅作叙事锚点；此处无需配方。）
});